create table if not exists public.profile (
  id bigint primary key default 1 check (id = 1),
  full_name text not null default 'MD. Shoriful Islam (Sakib)',
  short_name text default 'Sakib',
  headline text default 'Creative Developer & Digital Problem Solver',
  hero_text text,
  about_title text,
  bio text,
  availability text default 'Available for opportunities',
  location text default 'Bangladesh',
  email text,
  phone text,
  avatar_url text,
  resume_url text,
  github_url text,
  linkedin_url text,
  facebook_url text,
  years_experience text default '2+',
  projects_count text default '15+',
  clients_count text default '10+',
  updated_at timestamptz default now()
);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  tech_stack text,
  category text default 'Web App',
  image_url text,
  live_url text,
  github_url text,
  featured boolean default false,
  sort_order integer default 0,
  created_at timestamptz default now()
);

create table if not exists public.skills (
  id bigint generated by default as identity primary key,
  name text not null,
  category text default 'Frontend',
  level integer default 80 check (level between 0 and 100),
  sort_order integer default 0
);

create table if not exists public.experiences (
  id bigint generated by default as identity primary key,
  title text not null,
  organization text,
  period text,
  description text,
  sort_order integer default 0
);

create table if not exists public.education (
  id bigint generated by default as identity primary key,
  degree text not null,
  institution text,
  period text,
  description text,
  sort_order integer default 0
);

create table if not exists public.services (
  id bigint generated by default as identity primary key,
  title text not null,
  icon text default 'code',
  description text,
  sort_order integer default 0
);

create table if not exists public.certifications (
  id bigint generated by default as identity primary key,
  title text not null,
  issuer text,
  year text,
  credential_url text,
  sort_order integer default 0
);

create table if not exists public.testimonials (
  id bigint generated by default as identity primary key,
  name text not null,
  role text,
  quote text,
  avatar_url text,
  sort_order integer default 0
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  email text not null check (char_length(email) between 3 and 180),
  subject text not null check (char_length(subject) between 1 and 160),
  message text not null check (char_length(message) between 1 and 4000),
  created_at timestamptz default now()
);

