-- Public can read portfolio content.
create policy "public read profile" on public.profile for select to anon, authenticated using (true);
create policy "public read projects" on public.projects for select to anon, authenticated using (true);
create policy "public read skills" on public.skills for select to anon, authenticated using (true);
create policy "public read experiences" on public.experiences for select to anon, authenticated using (true);
create policy "public read education" on public.education for select to anon, authenticated using (true);
create policy "public read services" on public.services for select to anon, authenticated using (true);
create policy "public read certifications" on public.certifications for select to anon, authenticated using (true);
create policy "public read testimonials" on public.testimonials for select to anon, authenticated using (true);

-- Authenticated admin can manage portfolio content.
create policy "admin manage profile" on public.profile for all to authenticated using (true) with check (true);
create policy "admin manage projects" on public.projects for all to authenticated using (true) with check (true);
create policy "admin manage skills" on public.skills for all to authenticated using (true) with check (true);
create policy "admin manage experiences" on public.experiences for all to authenticated using (true) with check (true);
create policy "admin manage education" on public.education for all to authenticated using (true) with check (true);
create policy "admin manage services" on public.services for all to authenticated using (true) with check (true);
create policy "admin manage certifications" on public.certifications for all to authenticated using (true) with check (true);
create policy "admin manage testimonials" on public.testimonials for all to authenticated using (true) with check (true);

-- Anyone can send a message, but only authenticated admin can read/delete messages.
create policy "public send messages" on public.messages for insert to anon, authenticated with check (true);
create policy "admin read messages" on public.messages for select to authenticated using (true);
create policy "admin delete messages" on public.messages for delete to authenticated using (true);

-- Public storage bucket for portfolio images and CV.
insert into storage.buckets (id, name, public, file_size_limit)
values ('portfolio', 'portfolio', true, 10485760)
on conflict (id) do update set public = true, file_size_limit = 10485760;

create policy "public read portfolio files"
on storage.objects for select to anon, authenticated
using (bucket_id = 'portfolio');

create policy "admin upload portfolio files"
on storage.objects for insert to authenticated
with check (bucket_id = 'portfolio');

create policy "admin update portfolio files"
on storage.objects for update to authenticated
using (bucket_id = 'portfolio') with check (bucket_id = 'portfolio');

create policy "admin delete portfolio files"
on storage.objects for delete to authenticated
using (bucket_id = 'portfolio');
